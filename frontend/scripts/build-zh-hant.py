"""Traditional Chinese (zh-Hant) console text, made from the Simplified text.

Run by hand after changing Chinese text, then commit the output:

    pip install opencc-python-reimplemented
    python scripts/build-zh-hant.py

OpenCC `s2tw` changes the characters only, never the wording (打印 stays 打印, not 列印).
Its known mistakes are put right in FIXES below; add to it when proofreading finds one.
Output: src/i18n/zhHant.ts (base app messages, the console's `x` messages and the idle hints).
"""
import io
import json
import os
import re
import sys

import opencc

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src')
CC = opencc.OpenCC('s2tw')

# whole-word corrections after conversion: (wrong, right)
FIXES = [
    ('一臺', '一台'),   # a count ("one printer") is written 台
    ('溼', '濕'),       # the common form
    ('賬號', '帳號'),
    ('頭髮', '頭發'),   # 喷头发热 → 噴頭發熱, not hair
    ('乾預', '干預'),
    ('乾擾', '干擾'),
]

STR = re.compile(r"(\w+): '((?:[^'\\]|\\.)*)'")


def block(path, start, end):
    s = io.open(path, encoding='utf-8').read()
    a = s.index(start) + len(start)
    b = s.index(end, a)
    out = {}
    for k, v in STR.findall(s[a:b]):
        out[k] = v.replace("\\'", "'").replace('\\\\', '\\')
    return out


def conv(v):
    t = CC.convert(v)
    for a, b in FIXES:
        t = t.replace(a, b)
    return t


def main():
    base = block(os.path.join(ROOT, 'i18n', 'index.ts'), '\n  zh: {', '\n  en: {')
    x = block(os.path.join(ROOT, 'lcars', 'i18n.ts'), '\nconst zh = {', '\n}\n')
    hints = json.load(io.open(os.path.join(ROOT, 'assets', 'hints.json'), encoding='utf-8'))['zh']
    if len(base) < 100 or len(x) < 300:
        sys.exit(f'too few messages found ({len(base)} base, {len(x)} console): has the file layout changed?')

    msgs = {k: conv(v) for k, v in base.items()}
    msgs['x'] = {k: conv(v) for k, v in x.items()}
    out = (
        '/* Generated by scripts/build-zh-hant.py from the Simplified text: do not edit by hand.\n'
        '   Change the Simplified text (or FIXES in the script) and run the script again. */\n'
        f'export const zhHant = {json.dumps(msgs, ensure_ascii=False, indent=2)}\n\n'
        f'export const zhHantHints: string[] = {json.dumps([conv(h) for h in hints], ensure_ascii=False, indent=2)}\n'
    )
    io.open(os.path.join(ROOT, 'i18n', 'zhHant.ts'), 'w', encoding='utf-8', newline='\n').write(out)
    if '--show' in sys.argv:
        for k, v in list(base.items()) + list(x.items()):
            t = conv(v)
            if t != v:
                print(f'{k}\t{v}\t{t}')
    print(f'zhHant.ts: {len(base)} base + {len(x)} console messages, {len(hints)} hints')


if __name__ == '__main__':
    main()
