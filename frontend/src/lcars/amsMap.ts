/* Filament to AMS slot mapping for starting a print from the library.

   A sliced .3mf lists, per plate, the project filaments the plate uses (slice_info.config:
   <filament id="2" type="PETG" color="#FF0000" .../>, id 1-based). The print command takes
   ams_mapping: one entry per project filament, the tray to feed it from, -1 when unused.
   A tray is ams_id * 4 + slot for a 4-slot AMS. The external spool (254) is not offered:
   a P1S cannot feed one job from both the AMS and the external spool, and the spool holder has
   no sensor, so its stored type may describe a spool long gone; with "use AMS" off the printer
   takes the external spool. */
import type { DevicePrint } from '@bambulab-p1screen/printer-api'

export type FileFilament = { id: number, type: string, color: string }
export type Tray = { value: number, label: string, type: string, color: string }

export const EXTERNAL_TRAY = 254

/* The filaments one plate uses; the plate with that index, else the first plate listed.
   Plain text matching rather than DOMParser: the file is generated by the slicer, and this
   also runs where there is no DOM (tests). */
const attr = (tag: string, name: string) => new RegExp(`\\s${name}="([^"]*)"`).exec(tag)?.[1] ?? ''
export const parsePlateFilaments = (xml: string, plate?: string): FileFilament[] => {
  const plates = [...xml.matchAll(/<plate>([\s\S]*?)<\/plate>/g)].map(m => m[1])
  const body = plates.find(p => /<metadata\s+key="index"\s+value="([^"]*)"/.exec(p)?.[1] === plate) ?? plates[0]
  if (!body) return []
  const out: FileFilament[] = []
  for (const m of body.matchAll(/<filament\s[^>]*>/g)) {
    const id = Number(attr(m[0], 'id'))
    if (!Number.isInteger(id) || id < 1) continue
    out.push({ id, type: attr(m[0], 'type').trim(), color: normColor(attr(m[0], 'color')) })
  }
  return out.sort((a, b) => a.id - b.id)
}

/* '#RRGGBB' from '#RRGGBB', 'RRGGBBAA' or similar; '' when unreadable */
export const normColor = (c: string) => {
  const hex = c.replace(/^#/, '').trim()
  return /^[0-9a-f]{6}([0-9a-f]{2})?$/i.test(hex) ? `#${hex.slice(0, 6).toUpperCase()}` : ''
}

/* Loaded trays: every AMS slot that reports a filament type. */
export const loadedTrays = (p: DevicePrint | undefined): Tray[] => {
  const out: Tray[] = []
  for (const ams of p?.ams?.ams ?? []) {
    const amsId = Number(ams.id)
    if (!Number.isInteger(amsId)) continue
    for (const tray of ams.tray ?? []) {
      const slot = Number(tray.id)
      if (!tray.tray_type || !Number.isInteger(slot)) continue
      // AMS HT units (ids from 128) hold one spool; the firmware addresses it by the unit id
      const ht = amsId >= 128
      out.push({
        value: ht ? amsId : amsId * 4 + slot,
        label: ht ? `HT${amsId - 127}` : `${String.fromCharCode(65 + amsId)}${slot + 1}`,
        type: tray.tray_type,
        color: normColor(tray.tray_color ?? ''),
      })
    }
  }
  return out
}

const rgb = (c: string) => (c ? [1, 3, 5].map(i => parseInt(c.slice(i, i + 2), 16)) : null)
const colorDistance = (a: string, b: string) => {
  const x = rgb(a), y = rgb(b)
  if (!x || !y) return 1e6
  // weighted RGB distance: close enough to how different two spools look
  return 2 * (x[0] - y[0]) ** 2 + 4 * (x[1] - y[1]) ** 2 + 3 * (x[2] - y[2]) ** 2
}
const sameType = (a: string, b: string) => a.trim().toUpperCase() === b.trim().toUpperCase()

/* A tray for each filament: the same type with the nearest colour, a tray not already taken
   when there is one. null when no loaded tray has that type. */
export const autoMap = (fils: FileFilament[], trays: Tray[]): Record<number, number | null> => {
  const out: Record<number, number | null> = {}
  const taken = new Set<number>()
  for (const f of fils) {
    const same = trays.filter(t => sameType(t.type, f.type))
    const pool = same.filter(t => !taken.has(t.value))
    const pick = (pool.length ? pool : same).sort((a, b) => colorDistance(a.color, f.color) - colorDistance(b.color, f.color))[0]
    out[f.id] = pick ? pick.value : null
    if (pick) taken.add(pick.value)
  }
  return out
}

/* The ams_mapping array for the print command: index = project filament id - 1. */
export const toAmsMapping = (fils: FileFilament[], map: Record<number, number | null>): number[] => {
  const n = fils.reduce((m, f) => Math.max(m, f.id), 0)
  const out = Array.from({ length: n }, () => -1)
  for (const f of fils) {
    const v = map[f.id]
    if (v !== null && v !== undefined) out[f.id - 1] = v
  }
  return out
}
